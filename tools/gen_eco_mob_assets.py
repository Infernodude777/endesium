def main():
    for m in MOBS:
        mid = m["id"]
        # geo
        with open(os.path.join(GEO_DIR, f"{mid}.geo.json"), "w") as f:
            json.dump(geo_file(mid, m["tex_w"], m["tex_h"], m["bounds"], m["bones"]), f, indent="\t")
            f.write("\n")
        # animation
        with open(os.path.join(ANIM_DIR, f"{mid}.animation.json"), "w") as f:
            json.dump(anim_file(m["anims"]), f, indent="  ")
            f.write("\n")
        # art spec (for DogSprite driver) + fallback texture
        art = {"id": mid, "width": m["tex_w"], "height": m["tex_h"],
               "palette": m["pal"], "grid": m["tex"]}
        with open(os.path.join(ART_DIR, f"{mid}.json"), "w") as f:
            json.dump(art, f)
        write_png(os.path.join(TEX_DIR, f"{mid}.png"), m["tex"], m["pal"])
        print(f"wrote {mid}: geo + animation + texture + art")


if __name__ == "__main__":
    main()
